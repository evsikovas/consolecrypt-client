"""Typed Dart facade for imported WSLc features over CC's JSON bridge."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
source = (root / 'rust/wslc-core/src/api/desk.rs').read_text(encoding='utf-8')
def camel(name):
    parts = name.split('_')
    return parts[0] + ''.join(p.title() for p in parts[1:])
def dart(kind):
    kind = kind.strip()
    if kind.startswith('AppResult<'): return dart(kind[10:-1])
    if kind.startswith('Option<'): return dart(kind[7:-1]) + '?'
    if kind == 'Vec<u8>': return 'Uint8List'
    if kind.startswith('Vec<'): return 'List<' + dart(kind[4:-1]) + '>'
    return {'()':'void','u64':'BigInt','u16':'int','u32':'int','i64':'int','f64':'double'}.get(kind,kind)
def decode(kind, value):
    if kind.endswith('?'): return f'{value} == null ? null : {decode(kind[:-1], value)}'
    if kind.startswith('List<'): return f'({value} as List).map((item) => {decode(kind[5:-1], "item")}).toList()'
    if kind == 'String': return f'{value} as String'
    if kind == 'bool': return f'{value} as bool'
    if kind == 'BigInt': return f'BigInt.parse({value}.toString())'
    return f'{kind}.fromJson(({value} as Map).cast<String,dynamic>())'
methods = []
for fn in re.finditer(r'pub (async )?fn (\w+)\s*\((.*?)\)\s*(?:->\s*([^\{]+))?\s*\{', source, re.S):
    asynchronous, name, params, result = fn.groups()
    if name == 'disconnect': continue
    if name == 'registry_login':
        methods.append('  Future<void> registryLogin({String? server, required String username, required String password}) => login(server:server, username:username, password:password);')
        continue
    if name == 'shutdown_readers':
        methods.append('  Future<void> shutdownReaders() => close();')
        continue
    parsed = []
    for param in params.strip().strip(',').split(','):
        if not param.strip(): continue
        key, kind = param.strip().split(':',1)
        parsed.append((key.strip(),dart(kind)))
    signature = ', '.join(('' if kind.endswith('?') else 'required ') + kind + ' ' + camel(key) for key,kind in parsed)
    signature = '{' + signature + '}' if signature else ''
    out = dart(result.strip()) if result else 'void'
    if not asynchronous:
        assert name in {'preview_run_command','copy_run_command'}
        methods.append(f'  String {camel(name)}({signature}) => native.wslcPreview(specJson:jsonEncode(spec.toJson()), copy:{str(name == "copy_run_command").lower()});')
        continue
    arguments = '{' + ', '.join(f"'{key}':{camel(key)}" for key,_ in parsed) + '}'
    call = f"await request('{name}', {arguments})"
    body = f'{{ {call}; }}' if out == 'void' else f'{{ final value = {call}; return {decode(out,"value")}; }}'
    methods.append(f'  Future<{out}> {camel(name)}({signature}) async {body}')
text = '''// Generated by client/scripts/generate-wslc-dart-api.py.
import 'dart:convert';
import 'dart:typed_data';
import 'package:consolecrypt/src/rust/api/wslc.dart' as native;
import 'package:consolecrypt/wslc/src/rust/models.dart';
import 'package:consolecrypt/wslc/src/rust/api/transport.dart';
export 'package:consolecrypt/wslc/src/rust/api/transport.dart' show WslcReveal;
class WslcApi extends WslcTransport {
  WslcApi({required super.profileId, required super.reveal});
''' + '\n'.join(methods) + '\n}\n'
out = root / 'flutter/lib/wslc/src/rust/api/desk.dart'
out.parent.mkdir(parents=True,exist_ok=True)
out.write_text(text,encoding='utf-8',newline='\n')
print(f'Generated {len(methods)} instance methods; no separate native runtime')
