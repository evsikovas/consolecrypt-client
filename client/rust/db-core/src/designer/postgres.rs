/// `format_type` spellings and their short names (what the designer shows).
pub(super) const ALIASES: &[(&str, &str)] = &[
    ("character varying", "varchar"),
    ("character", "char"),
    ("timestamp with time zone", "timestamptz"),
    ("timestamp without time zone", "timestamp"),
    ("time with time zone", "timetz"),
    ("time without time zone", "time"),
    ("bit varying", "varbit"),
    ("int", "integer"),
    ("int4", "integer"),
    ("int8", "bigint"),
    ("int2", "smallint"),
    ("float8", "double precision"),
    ("float4", "real"),
    ("bool", "boolean"),
    ("decimal", "numeric"),
];

pub(super) fn short_type(name: &str) -> String {
    let lower = name.trim().to_ascii_lowercase();
    ALIASES
        .iter()
        .find(|(long, _)| *long == lower)
        .map_or(lower.clone(), |(_, short)| (*short).to_owned())
}

impl Postgres {
    fn table(&self, design: &TableDesign) -> String {
        self.qualified(design.schema.as_deref(), &design.name)
    }

    fn qualified(&self, schema: Option<&str>, name: &str) -> String {
        match schema.filter(|schema| !schema.is_empty()) {
            Some(schema) => format!("{}.{}", self.quote(schema), self.quote(name)),
            None => self.quote(name),
        }
    }

    fn data_type(&self, column: &ColumnDesign) -> String {
        if column.identity == "serial" {
            return match short_type(&column.data_type).as_str() {
                "bigint" => "bigserial".into(),
                "smallint" => "smallserial".into(),
                _ => "serial".into(),
            };
        }
        let mut text = column_type(column);
        if column.array {
            text.push_str("[]");
        }
        text
    }

    fn column(&self, column: &ColumnDesign) -> String {
        let mut line = format!("{} {}", self.quote(&column.name), self.data_type(column));
        match column.identity.as_str() {
            "by_default" => line.push_str(" GENERATED BY DEFAULT AS IDENTITY"),
            "always" => line.push_str(" GENERATED ALWAYS AS IDENTITY"),
            _ => {}
        }
        if !column.nullable {
            line.push_str(" NOT NULL");
        }
        if !column.default.trim().is_empty() {
            line.push_str(" DEFAULT ");
            line.push_str(&default_sql(self, &column.default));
        }
        line
    }

    fn primary_key(&self, design: &TableDesign) -> String {
        let key = &design.primary_key;
        format!(
            "CONSTRAINT {} PRIMARY KEY ({})",
            self.quote(&name_or(&self.info(), &key.name, &design.name, &[], "pkey")),
            quote_list(self, &key.columns)
        )
    }

    fn unique(&self, design: &TableDesign, key: &KeyDesign) -> String {
        format!(
            "CONSTRAINT {} UNIQUE ({})",
            self.quote(&name_or(
                &self.info(),
                &key.name,
                &design.name,
                &key.columns,
                "key"
            )),
            quote_list(self, &key.columns)
        )
    }

    fn foreign_key(&self, design: &TableDesign, fk: &ForeignKeyDesign) -> String {
        let schema = fk
            .ref_schema
            .as_deref()
            .filter(|schema| !schema.is_empty())
            .or(design.schema.as_deref());
        let mut sql = format!(
            "CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {} ({})",
            self.quote(&name_or(
                &self.info(),
                &fk.name,
                &design.name,
                &fk.columns,
                "fkey"
            )),
            quote_list(self, &fk.columns),
            self.qualified(schema, &fk.ref_table),
            quote_list(self, &fk.ref_columns)
        );
        if !fk.on_delete.is_empty() {
            sql.push_str(&format!(" ON DELETE {}", fk.on_delete));
        }
        if !fk.on_update.is_empty() {
            sql.push_str(&format!(" ON UPDATE {}", fk.on_update));
        }
        sql
    }

    fn check(&self, design: &TableDesign, check: &CheckDesign) -> String {
        format!(
            "CONSTRAINT {} CHECK ({})",
            self.quote(&name_or(
                &self.info(),
                &check.name,
                &design.name,
                &[],
                "check"
            )),
            check.expression.trim()
        )
    }

    fn index(&self, design: &TableDesign, index: &IndexDesign) -> String {
        let mut sql = format!(
            "CREATE {}INDEX {} ON {}",
            if index.unique { "UNIQUE " } else { "" },
            self.quote(&name_or(
                &self.info(),
                &index.name,
                &design.name,
                &index.columns,
                "idx"
            )),
            self.table(design)
        );
        if !index.method.is_empty() {
            sql.push_str(&format!(" USING {}", index.method));
        }
        sql.push_str(&format!(" ({})", quote_list(self, &index.columns)));
        sql
    }

    fn comment(&self, target: &str, text: &str) -> String {
        let value = if text.is_empty() {
            "NULL".to_owned()
        } else {
            self.literal(text)
        };
        format!("COMMENT ON {target} IS {value}")
    }

    fn column_comment(&self, design: &TableDesign, column: &str, text: &str) -> String {
        self.comment(
            &format!("COLUMN {}.{}", self.table(design), self.quote(column)),
            text,
        )
    }
}

impl Dialect for Postgres {
    fn info(&self) -> DialectInfo {
        DialectInfo {
            engine: DbEngine::Postgresql,
            features: DesignFeatures {
                schemas: true,
                primary_key: true,
                unique: true,
                foreign_keys: true,
                checks: true,
                indexes: true,
                arrays: true,
                table_comment: true,
                column_comments: true,
                alter: true,
                transactional: true,
                ..Default::default()
            },
            types: TYPES.to_vec(),
            default_type: "integer",
            identity_kinds: vec!["by_default", "always", "serial"],
            default_presets: vec![
                "now()",
                "CURRENT_TIMESTAMP",
                "CURRENT_DATE",
                "gen_random_uuid()",
                "0",
                "''",
                "true",
                "false",
                "'{}'::jsonb",
            ],
            index_methods: vec!["btree", "hash", "gin", "gist", "brin", "spgist"],
            fk_actions: vec![
                "NO ACTION",
                "RESTRICT",
                "CASCADE",
                "SET NULL",
                "SET DEFAULT",
            ],
            options: vec![
                OptionInfo {
                    id: "partition_by",
                    kind: OptionKind::Choice,
                    choices: vec!["", "RANGE", "LIST", "HASH"],
                    default: "",
                    create_only: true,
                },
                OptionInfo {
                    id: "partition_key",
                    kind: OptionKind::Text,
                    choices: vec![],
                    default: "",
                    create_only: true,
                },
                OptionInfo {
                    id: "unlogged",
                    kind: OptionKind::Bool,
                    choices: vec![],
                    default: "false",
                    create_only: false,
                },
            ],
            max_identifier: 63,
        }
    }

    fn quote(&self, name: &str) -> String {
        format!("\"{}\"", name.replace('"', "\"\""))
    }

    fn literal(&self, text: &str) -> String {
        format!("'{}'", text.replace('\'', "''"))
    }

    fn validate(&self, design: &TableDesign, issues: &mut Issues) {
        let info = self.info();
        let by = option(&info, design, "partition_by");
        let key = option(&info, design, "partition_key");
        if !by.is_empty() && key.trim().is_empty() {
            issues.error("partition_key_required", "options.partition_key", "");
        }
        // PostgreSQL refuses an unlogged partitioned table.
        if !by.is_empty() && option(&info, design, "unlogged") == "true" {
            issues.error("unlogged_partitioned", "options.unlogged", "");
        }
        if !by.is_empty() && !design.primary_key.columns.is_empty() {
            // A partitioned table's primary key must include the partition key.
            let key = key.replace('"', "");
            let covered = key
                .split(',')
                .map(str::trim)
                .all(|part| design.primary_key.columns.iter().any(|c| c == part));
            if !covered {
                issues.warning(
                    "partition_key_not_in_primary_key",
                    "options.partition_key",
                    &key,
                );
            }
        }
        for (i, column) in design.columns.iter().enumerate() {
            if column.identity == "serial"
                && !matches!(
                    short_type(&column.data_type).as_str(),
                    "integer" | "bigint" | "smallint"
                )
            {
                issues.error(
                    "identity_type",
                    format!("columns.{i}.identity"),
                    &column.name,
                );
            }
            if matches!(column.identity.as_str(), "by_default" | "always")
                && !matches!(
                    short_type(&column.data_type).as_str(),
                    "integer" | "bigint" | "smallint"
                )
            {
                issues.error(
                    "identity_type",
                    format!("columns.{i}.identity"),
                    &column.name,
                );
            }
        }
    }

    fn create(&self, design: &TableDesign, _: &mut Issues) -> Vec<DesignStatement> {
        let info = self.info();
        let mut lines: Vec<String> = design.columns.iter().map(|c| self.column(c)).collect();
        if !design.primary_key.columns.is_empty() {
            lines.push(self.primary_key(design));
        }
        lines.extend(design.uniques.iter().map(|key| self.unique(design, key)));
        lines.extend(design.checks.iter().map(|check| self.check(design, check)));
        lines.extend(
            design
                .foreign_keys
                .iter()
                .map(|fk| self.foreign_key(design, fk)),
        );
        let unlogged = if option(&info, design, "unlogged") == "true" {
            "UNLOGGED "
        } else {
            ""
        };
        let mut sql = format!(
            "CREATE {unlogged}TABLE {} (\n    {}\n)",
            self.table(design),
            lines.join(",\n    ")
        );
        let by = option(&info, design, "partition_by");
        if !by.is_empty() {
            sql.push_str(&format!(
                " PARTITION BY {by} ({})",
                partition_key(self, design, option(&info, design, "partition_key"))
            ));
        }
        let mut statements = vec![statement(sql)];
        statements.extend(
            design
                .indexes
                .iter()
                .map(|index| statement(self.index(design, index))),
        );
        if !design.comment.is_empty() {
            statements.push(statement(
                self.comment(&format!("TABLE {}", self.table(design)), &design.comment),
            ));
        }
        for column in &design.columns {
            if !column.comment.is_empty() {
                statements.push(statement(self.column_comment(
                    design,
                    &column.name,
                    &column.comment,
                )));
            }
        }
        statements
    }

    fn alter(
        &self,
        before: &TableDesign,
        after: &TableDesign,
        changes: &TableChanges<'_>,
        issues: &mut Issues,
    ) -> Vec<DesignStatement> {
        let info = self.info();
        if before.schema != after.schema {
            issues.error(
                "move_unsupported",
                "table.schema",
                after.schema.as_deref().unwrap_or(""),
            );
        }
        let mut persistence = None;
        for id in &changes.changed_options {
            if *id == "unlogged" {
                persistence = Some(option(&info, after, "unlogged") == "true");
            } else {
                issues.error("option_create_only", format!("options.{id}"), id);
            }
        }
        // Everything addresses the table by its current name; a rename runs last.
        let current = TableDesign {
            name: before.name.clone(),
            schema: before.schema.clone(),
            ..Default::default()
        };
        let table = self.table(&current);
        let alter = |op: String| format!("ALTER TABLE {table} {op}");
        let mut out = Vec::new();
        if let Some(unlogged) = persistence {
            // Rewrites the table; UNLOGGED data is lost after a crash.
            out.push(statement(alter(
                if unlogged {
                    "SET UNLOGGED"
                } else {
                    "SET LOGGED"
                }
                .to_owned(),
            )));
        }
        let named = |name: &str, columns: &[String], suffix: &str| {
            name_or(&info, name, &before.name, columns, suffix)
        };
        for fk in &changes.dropped_foreign_keys {
            let name = named(&fk.name, &fk.columns, "fkey");
            out.push(statement(alter(format!(
                "DROP CONSTRAINT {}",
                self.quote(&name)
            ))));
        }
        for check in &changes.dropped_checks {
            let name = named(&check.name, &[], "check");
            out.push(statement(alter(format!(
                "DROP CONSTRAINT {}",
                self.quote(&name)
            ))));
        }
        for key in &changes.dropped_uniques {
            let name = named(&key.name, &key.columns, "key");
            out.push(statement(alter(format!(
                "DROP CONSTRAINT {}",
                self.quote(&name)
            ))));
        }
        for index in &changes.dropped_indexes {
            let name = named(&index.name, &index.columns, "idx");
            out.push(statement(format!(
                "DROP INDEX {}",
                self.qualified(before.schema.as_deref(), &name)
            )));
        }
        if changes.primary_key_changed && !before.primary_key.columns.is_empty() {
            out.push(destructive(alter(format!(
                "DROP CONSTRAINT {}",
                self.quote(&name_or(
                    &info,
                    &before.primary_key.name,
                    &before.name,
                    &[],
                    "pkey"
                ))
            ))));
        }
        for column in &changes.dropped_columns {
            out.push(destructive(alter(format!(
                "DROP COLUMN {}",
                self.quote(&column.name)
            ))));
        }
        for (old, new, _) in &changes.kept_columns {
            if old.name != new.name {
                out.push(statement(alter(format!(
                    "RENAME COLUMN {} TO {}",
                    self.quote(&old.name),
                    self.quote(&new.name)
                ))));
            }
        }
        for (i, (old, new, position)) in changes.kept_columns.iter().enumerate() {
            let _ = i;
            let name = self.quote(&new.name);
            let target = format!("columns.{position}");
            let old_type = (short_type(&old.data_type), old.length, old.scale, old.array);
            let new_type = (short_type(&new.data_type), new.length, new.scale, new.array);
            if old.identity != new.identity {
                match (old.identity.as_str(), new.identity.as_str()) {
                    // ADD GENERATED below.
                    ("", "by_default" | "always") => {}
                    ("by_default" | "always", "") => {
                        out.push(statement(alter(format!(
                            "ALTER COLUMN {name} DROP IDENTITY"
                        ))));
                    }
                    ("by_default", "always") | ("always", "by_default") => {
                        out.push(statement(alter(format!(
                            "ALTER COLUMN {name} SET GENERATED {}",
                            if new.identity == "always" {
                                "ALWAYS"
                            } else {
                                "BY DEFAULT"
                            }
                        ))));
                    }
                    // serial is a sequence default, not an identity.
                    _ => issues.error(
                        "identity_change_unsupported",
                        format!("{target}.identity"),
                        &new.name,
                    ),
                }
            }
            if old_type != new_type {
                let data_type = self.data_type(new);
                out.push(destructive(alter(format!(
                    "ALTER COLUMN {name} TYPE {data_type} USING {name}::{data_type}"
                ))));
            }
            if old.nullable != new.nullable {
                out.push(statement(alter(format!(
                    "ALTER COLUMN {name} {} NOT NULL",
                    if new.nullable { "DROP" } else { "SET" }
                ))));
            }
            if old.default.trim() != new.default.trim() {
                out.push(statement(alter(if new.default.trim().is_empty() {
                    format!("ALTER COLUMN {name} DROP DEFAULT")
                } else {
                    format!(
                        "ALTER COLUMN {name} SET DEFAULT {}",
                        default_sql(self, &new.default)
                    )
                })));
            }
            if old.identity.is_empty() && matches!(new.identity.as_str(), "by_default" | "always") {
                out.push(statement(alter(format!(
                    "ALTER COLUMN {name} ADD GENERATED {} AS IDENTITY",
                    if new.identity == "always" {
                        "ALWAYS"
                    } else {
                        "BY DEFAULT"
                    }
                ))));
            }
        }
        for (position, column) in &changes.added_columns {
            if !column.nullable && column.default.trim().is_empty() && column.identity.is_empty() {
                issues.warning(
                    "not_null_without_default",
                    format!("columns.{position}.nullable"),
                    &column.name,
                );
            }
            out.push(statement(alter(format!(
                "ADD COLUMN {}",
                self.column(column)
            ))));
        }
        if changes.primary_key_changed && !after.primary_key.columns.is_empty() {
            let design = TableDesign {
                name: after.name.clone(),
                primary_key: after.primary_key.clone(),
                ..Default::default()
            };
            out.push(statement(alter(format!(
                "ADD {}",
                self.primary_key(&design)
            ))));
        }
        for key in &changes.added_uniques {
            out.push(statement(alter(format!("ADD {}", self.unique(after, key)))));
        }
        for check in &changes.added_checks {
            out.push(statement(alter(format!(
                "ADD {}",
                self.check(after, check)
            ))));
        }
        for fk in &changes.added_foreign_keys {
            out.push(statement(alter(format!(
                "ADD {}",
                self.foreign_key(after, fk)
            ))));
        }
        for index in &changes.added_indexes {
            out.push(statement(self.index(&current, index)));
        }
        if changes.comment_changed {
            out.push(statement(
                self.comment(&format!("TABLE {table}"), &after.comment),
            ));
        }
        for (old, new, _) in &changes.kept_columns {
            if old.comment != new.comment {
                out.push(statement(self.column_comment(
                    &current,
                    &new.name,
                    &new.comment,
                )));
            }
        }
        for (_, column) in &changes.added_columns {
            if !column.comment.is_empty() {
                out.push(statement(self.column_comment(
                    &current,
                    &column.name,
                    &column.comment,
                )));
            }
        }
        if changes.renamed_table {
            out.push(statement(alter(format!(
                "RENAME TO {}",
                self.quote(&after.name)
            ))));
        }
        out
    }
}

/// Partition key: column names are quoted, anything else is an expression.
fn partition_key(dialect: &Postgres, design: &TableDesign, key: &str) -> String {
    key.split(',')
        .map(str::trim)
        .map(|part| {
            if design.columns.iter().any(|column| column.name == part) {
                dialect.quote(part)
            } else {
                part.to_owned()
            }
        })
        .collect::<Vec<_>>()
        .join(", ")
}

