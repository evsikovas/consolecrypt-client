    #[test]
    fn alters_columns_keys_and_names() {
        let before = loaded(orders());
        let mut after = before.clone();
        after.name = "purchase".into();
        after.comment = String::new();
        after.columns.retain(|c| c.name != "tags");
        let status = after
            .columns
            .iter_mut()
            .find(|c| c.name == "status")
            .unwrap();
        status.name = "state".into();
        status.length = Some(200);
        status.nullable = true;
        status.default = String::new();
        status.comment = "State".into();
        after.columns.push(ColumnDesign {
            nullable: false,
            default: "0".into(),
            ..column("weight", "integer")
        });
        after.uniques.clear();
        after.indexes.push(IndexDesign {
            name: "purchase_state_idx".into(),
            columns: vec!["state".into()],
            ..Default::default()
        });
        let plan = make_plan(DbEngine::Postgresql, Some(&before), &after);
        let sql: Vec<(&str, bool)> = plan
            .statements
            .iter()
            .map(|s| (s.sql.as_str(), s.destructive))
            .collect();
        let t = "ALTER TABLE \"public\".\"orders\"";
        assert_eq!(
            sql,
            [
                (format!("{t} DROP CONSTRAINT \"orders_select_key\"").as_str(), false),
                (format!("{t} DROP COLUMN \"tags\"").as_str(), true),
                (format!("{t} RENAME COLUMN \"status\" TO \"state\"").as_str(), false),
                (
                    format!("{t} ALTER COLUMN \"state\" TYPE varchar(200) USING \"state\"::varchar(200)").as_str(),
                    true
                ),
                (format!("{t} ALTER COLUMN \"state\" DROP NOT NULL").as_str(), false),
                (format!("{t} ALTER COLUMN \"state\" DROP DEFAULT").as_str(), false),
                (format!("{t} ADD COLUMN \"weight\" integer NOT NULL DEFAULT 0").as_str(), false),
                (
                    "CREATE INDEX \"purchase_state_idx\" ON \"public\".\"orders\" (\"state\")",
                    false
                ),
                ("COMMENT ON TABLE \"public\".\"orders\" IS NULL", false),
                (
                    "COMMENT ON COLUMN \"public\".\"orders\".\"state\" IS 'State'",
                    false
                ),
                (format!("{t} RENAME TO \"purchase\"").as_str(), false),
            ]
        );
        assert_guard_accepts(DbEngine::Postgresql, &plan);
    }

