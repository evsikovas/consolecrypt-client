//! Portable Vault/OpenBao connections, one independently encrypted record per
//! connection. The existing Other-secret wire type is opaque to older clients:
//! a generic VaultSettings save cannot drop these records. Login material lives
//! in its separate Credential/Secret. The working set indexes only this DTO.
use crate::{session::Unlocked, AppError, AppResult};
use cc_models::{
    credential::CredentialKind,
    secret::{Secret, SecretKind, SecretValue},
    ObjectId, VaultObject,
};
use serde::{Deserialize, Serialize};
use sha2::{Digest, Sha256};
use std::collections::{BTreeMap, BTreeSet};

const RECORD_PREFIX: &str = "consolecrypt:external-vault:v1\n";
const MAX_CONNECTIONS: usize = 256;

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ExternalVaultConfig {
    pub id: String,
    pub name: String,
    pub endpoint: String,
    pub auth: String,
    pub username: String,
    pub auth_mount: String,
    pub mount: String,
    pub namespace: String,
    pub versioned: bool,
    pub credential_id: Option<ObjectId>,
}

fn invalid() -> AppError {
    AppError::invalid("external_vaults", "invalid connection or concurrent change")
}

fn path(raw: &str) -> bool {
    raw.len() <= 2048
        && raw.split('/').all(|segment| {
            !segment.is_empty()
                && segment != "."
                && segment != ".."
                && !segment
                    .chars()
                    .any(|c| c.is_control() || matches!(c, '%' | '\\'))
        })
}

impl ExternalVaultConfig {
    fn object_id(&self) -> ObjectId {
        // IDs generated by the client carry 144 random bits. A separate domain
        // avoids collisions with login material and exposes no type prefix.
        let mut digest = Sha256::new();
        digest.update(b"consolecrypt/external-vault/metadata/v1\0");
        digest.update(self.id.as_bytes());
        let hash = digest.finalize();
        let mut bytes = [0; 16];
        bytes.copy_from_slice(&hash[..16]);
        ObjectId::from_uuid(uuid::Uuid::from_bytes(bytes))
    }

    fn valid(&self) -> bool {
        let Ok(url) = url::Url::parse(&self.endpoint) else {
            return false;
        };
        !self.id.is_empty()
            && self.id.len() <= 100
            && self
                .id
                .bytes()
                .all(|c| c.is_ascii_alphanumeric() || b"-_=".contains(&c))
            && !self.name.trim().is_empty()
            && self.name.chars().count() <= 120
            && !self.name.chars().any(char::is_control)
            && self.endpoint.len() <= 4096
            && !self.endpoint.chars().any(char::is_control)
            && matches!(url.scheme(), "http" | "https")
            && url.host().is_some()
            && url.username().is_empty()
            && url.password().is_none()
            && url.query().is_none()
            && url.fragment().is_none()
            && path(&self.mount)
            && (self.namespace.is_empty() || self.namespace.is_ascii() && path(&self.namespace))
            && match self.auth.as_str() {
                "token" => self.auth_mount.is_empty() && self.username.is_empty(),
                "userpass" => {
                    path(&self.auth_mount)
                        && self.username.len() <= 256
                        && !self.username.contains('/')
                        && path(&self.username)
                }
                _ => false,
            }
    }

    fn same_identity(&self, other: &Self) -> bool {
        self.endpoint == other.endpoint
            && self.auth == other.auth
            && self.username == other.username
            && self.auth_mount == other.auth_mount
            && self.namespace == other.namespace
            && self.mount == other.mount
            && self.versioned == other.versioned
    }
}

pub(crate) fn connection_record(secret: &Secret) -> Option<ExternalVaultConfig> {
    if secret.kind != SecretKind::Other {
        return None;
    }
    let json = secret.value.expose_secret().strip_prefix(RECORD_PREFIX)?;
    if json.len() > 32_768 {
        return None;
    }
    let config: ExternalVaultConfig = serde_json::from_str(json).ok()?;
    (config.object_id() == secret.id && config.valid()).then_some(config)
}

fn indexed(rows: &[ExternalVaultConfig]) -> AppResult<BTreeMap<&str, &ExternalVaultConfig>> {
    if rows.len() > MAX_CONNECTIONS {
        return Err(invalid());
    }
    let mut index = BTreeMap::new();
    for row in rows {
        if !row.valid() || index.insert(row.id.as_str(), row).is_some() {
            return Err(invalid());
        }
    }
    Ok(index)
}

pub(crate) async fn save_changes(
    u: &Unlocked,
    original: &[ExternalVaultConfig],
    edited: &[ExternalVaultConfig],
) -> AppResult<()> {
    let _guard = u.external_vault_edits.lock().await;
    let before = indexed(original)?;
    let after = indexed(edited)?;
    let current_rows = u.working().external_vaults();
    let current = indexed(&current_rows)?;
    let ids: BTreeSet<_> = before.keys().chain(after.keys()).copied().collect();
    let mut changes = Vec::new();
    let mut total = current.len();
    for id in ids {
        let from = before.get(id).copied();
        let to = after.get(id).copied();
        let live = current.get(id).copied();
        if from == to || live == to {
            continue;
        }
        if live != from {
            return Err(invalid());
        }
        let oid = to.or(from).expect("union contains the id").object_id();
        if u.working().vault_of(oid).is_some()
            || (live.is_none() && u.working().kind_of(oid).is_some())
        {
            return Err(invalid());
        }
        if let Some(row) = to {
            if let Some(cred_id) = row.credential_id {
                if from.is_some_and(|old| {
                    old.credential_id == Some(cred_id) && !old.same_identity(row)
                }) || u.working().vault_of(cred_id).is_some()
                    || !u.working().credential(cred_id).is_some_and(|c| {
                        c.kind == CredentialKind::Password && c.secret_id.is_some()
                    })
                {
                    return Err(invalid());
                }
            }
            if live.is_none() {
                total += 1;
            }
        } else {
            total -= 1;
        }
        changes.push((oid, to));
    }
    if total > MAX_CONNECTIONS {
        return Err(invalid());
    }
    for (oid, row) in changes {
        if let Some(row) = row {
            let json = serde_json::to_string(row).map_err(|_| invalid())?;
            let mut record = Secret::new(
                SecretKind::Other,
                SecretValue::new(format!("{RECORD_PREFIX}{json}")),
            );
            record.id = oid;
            u.writer.put_in(None, VaultObject::Secret(record)).await?;
        } else {
            u.writer.delete(oid).await?;
        }
    }
    Ok(())
}

/// A password credential can be referenced by a portable connection or another
/// synced setting, and a DB/Kubernetes connection can reference its secret.
pub(crate) fn credential_in_use(u: &Unlocked, id: ObjectId) -> bool {
    let ws = u.working();
    if ws
        .external_vaults()
        .iter()
        .any(|row| row.credential_id == Some(id))
    {
        return true;
    }
    if ws.all_vault_settings().into_iter().any(|s| {
        crate::teams::references(ws, &VaultObject::VaultSettings(s)).contains(&id)
    }) {
        return true;
    }
    let Some(secret) = ws.credential(id).and_then(|c| c.secret_id) else {
        return false;
    };
    ws.db_connections()
        .iter()
        .any(|db| db.auth.secret_ids().contains(&secret))
        || ws
            .kube_contexts()
            .iter()
            .any(|ctx| ctx.auth.secret_ids().contains(&secret))
        || ws
            .proxies()
            .iter()
            .any(|proxy| proxy.password_secret_id == Some(secret))
        || ws.credentials().iter().any(|c| {
            c.id != id && (c.secret_id == Some(secret) || c.passphrase_secret_id == Some(secret))
        })
}
