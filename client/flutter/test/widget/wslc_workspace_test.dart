    expect(api.calls, contains('list_containers'));
    await tester.tap(find.text('fixture-web').first);
    await settle(tester);
    await tester.tap(find.text('Окружение').first);
    await settle(tester);
    await tester.tap(find.byTooltip('Скопировать значение').first);
    await settle(tester);
    expect(clipboard.values, ['synthetic-test-token']);
    await tester.tap(find.text('Терминал').last);
    await settle(tester);
    expect(find.byType(TerminalView), findsOneWidget);
    await tester.tap(find.byType(TerminalView));
    final view = tester.widget<TerminalView>(find.byType(TerminalView));
    const selected = 'synthetic-terminal-token';
    view.terminal.write('\x1b[2J\x1b[H$selected');
    view.controller!.setSelection(
      view.terminal.buffer.createAnchor(0, 0),
      view.terminal.buffer.createAnchor(selected.length, 0),
    );
    await tester.sendKeyDownEvent(LogicalKeyboardKey.controlLeft);
    await tester.sendKeyDownEvent(LogicalKeyboardKey.shiftLeft);
    await tester.sendKeyEvent(LogicalKeyboardKey.keyC);
    await tester.sendKeyUpEvent(LogicalKeyboardKey.shiftLeft);
    await tester.sendKeyUpEvent(LogicalKeyboardKey.controlLeft);
    await settle(tester);
    expect(clipboard.values.last, selected);
    api.writes.clear();
    var reads = 0;
    tester.binding.defaultBinaryMessenger.setMockMethodCallHandler(SystemChannels.platform, (call) async {
      if (call.method != 'Clipboard.getData') return null;
      reads++;
      return {'text': 'echo first\necho second\n'};
    });
    addTearDown(() => tester.binding.defaultBinaryMessenger.setMockMethodCallHandler(SystemChannels.platform, null));
    await tester.sendKeyDownEvent(LogicalKeyboardKey.controlLeft);
    await tester.sendKeyDownEvent(LogicalKeyboardKey.keyV);
    await tester.sendKeyRepeatEvent(LogicalKeyboardKey.keyV);
    await tester.sendKeyUpEvent(LogicalKeyboardKey.keyV);
    await tester.sendKeyUpEvent(LogicalKeyboardKey.controlLeft);
    await settle(tester);
    expect(reads, 1);
    expect(api.writes, isEmpty);
    await tapKey(tester, 'confirm-cancel');
    expect(api.writes, isEmpty);
    await tester.tap(find.byType(TerminalView));
    await tester.sendKeyDownEvent(LogicalKeyboardKey.controlLeft);
    await tester.sendKeyEvent(LogicalKeyboardKey.keyK);
    await tester.sendKeyUpEvent(LogicalKeyboardKey.controlLeft);
    await settle(tester);
    expect(find.byKey(const ValueKey('command-palette')), findsOneWidget);
    await tester.sendKeyEvent(LogicalKeyboardKey.escape);
    await settle(tester);
    final oldOutput = api.delayedOutput = Completer<TerminalOutput>();
    await tester.pump(const Duration(milliseconds: 40));
    await tester.tap(find.text('Новая сессия'));
    await settle(tester);
    expect(api.openedTerminals, 2);
    api.delayedOutput = null;
    oldOutput.complete(TerminalOutput(data: utf8.encode('stale terminal output'), alive: false));
    await settle(tester);
    final renewed = tester.widget<TerminalView>(find.byType(TerminalView));
    renewed.controller!.setSelection(
      renewed.terminal.buffer.createAnchor(0, 0),
      renewed.terminal.buffer.createAnchor(renewed.terminal.viewWidth, 1),
    );
    expect(renewed.terminal.buffer.getText(renewed.controller!.selection!).trim(), isEmpty);
    expect(api.closedTerminals, [BigInt.one]);
    final lateRead = Completer<Object?>();
    tester.binding.defaultBinaryMessenger.setMockMethodCallHandler(SystemChannels.platform, (call) {
      return call.method == 'Clipboard.getData' ? lateRead.future : Future.value();
    });
    await tester.tap(find.byType(TerminalView));
    await tester.sendKeyDownEvent(LogicalKeyboardKey.controlLeft);
    await tester.sendKeyEvent(LogicalKeyboardKey.keyV);
    await tester.sendKeyUpEvent(LogicalKeyboardKey.controlLeft);
    await backend.services.vault.lock();
    await settle(tester);
    lateRead.complete({'text': 'must never reach an expired terminal'});
    await settle(tester);
    expect(api.writes, isEmpty);
    expect(api.closed, isTrue);
    expect(find.byType(WslcWorkspace), findsNothing);
    expect(tester.takeException(), isNull);
  }, variant: TargetPlatformVariant.only(TargetPlatform.windows));
