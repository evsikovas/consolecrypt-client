class _Api extends WslcApi {
  _Api({required super.profileId, required super.reveal});
  final calls = <String>[];
  final writes = <String>[];
  final closedTerminals = <BigInt>[];
  Completer<TerminalOutput>? delayedOutput;
  int openedTerminals = 0;
  bool closed = false;
  static final id = 'a' * 64;
  @override
  Future<dynamic> request(String operation, Map<String, dynamic> args) async {
    if (closed) throw expired;
    calls.add(operation);
    if (operation == 'write_terminal') writes.add(utf8.decode(args['data'] as List<int>));
    if (operation == 'close_terminal_session') closedTerminals.add(args['session'] as BigInt);
    if (operation == 'take_terminal_output' && delayedOutput != null) {
      return delayedOutput!.future.then((output) => output.toJson());
    }
    return switch (operation) {
      'load_settings' => const DeskSettings(templates: []).toJson(),
      'probe_runtime' => const RuntimeInfo(
        cliPath: r'C:\Program Files\WSL\wslc.exe',
        cliVersion: 'wslc 3.0.3.0',
        versionSupported: true,
        versionVerified: true,
        readable: true,
      ).toJson(),
      'list_containers' => [
        ContainerSummary(
          id: id,
          name: 'fixture-web',
          image: 'example.test/web:1',
          state: ContainerState.running,
        ).toJson(),
      ],
      'inspect_container' => ContainerDetails(
        id: id,
        name: 'fixture-web',
        state: ContainerState.running,
        ports: [],
        networks: [],
        inspectJson: '{}',
      ).toJson(),
      'container_env' => [const EnvEntry(key: 'API_TOKEN', value: 'synthetic-test-token', fromImage: false).toJson()],
      'take_events' => const EventBatch(events: [], running: false).toJson(),
      'list_images' || 'list_volumes' || 'list_networks' || 'container_stats' => [],
      'parse_compose' => demoComposePlan().toJson(),
      'open_terminal_session' => ++openedTerminals,
      'take_terminal_output' => TerminalOutput(data: Uint8List(0), alive: true).toJson(),
      _ => null,
    };
  }

  @override
  Future<void> close() async {
    closed = true;
    await super.close();
  }
}

class _Ai extends Fake implements AiService {
  final events = StreamController<cc.AiStreamEvent>.broadcast();
  List<cc.ChatMessage> messages = [];
  cc.AiContextSelection? selection;
  int requests = 0;
  void dispose() => unawaited(events.close());
  @override
  Stream<List<cc.AiProviderConfig>> watchProviders() =>
      Stream.value([cc.AiProviderConfig.draft(cc.AiProviderKind.ollama)]);
  @override
  Stream<cc.AiStreamEvent> chat({
    required cc.ObjectId providerId,
    required List<cc.ChatMessage> history,
    cc.AiContextSelection context = cc.AiContextSelection.none,
  }) {
    messages = history;
    requests++;
    selection = context;
    return events.stream;
  }
}

class _Clipboard extends SecureClipboard {
  final values = <String>[];
  @override
  Future<void> copySecret(
    String value, {
    bool Function()? isCurrent,
    Duration? limit,
    bool autoGenerated = false,
  }) async {
    if (isCurrent?.call() ?? true) values.add(value);
  }
}

