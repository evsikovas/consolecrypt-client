class _Files extends Fake implements FileDialogService {
  _Files(this.path);
  final String path;
  final finished = <String>[];
  @override
  Future<bool> finishSaveFile(String path) async {
    finished.add(path);
    return true;
  }

  @override
  Future<String?> chooseSaveFile({required String suggestedName, List<String> extensions = const []}) async =>
      '${File(path).parent.path}/Export.kdbx';
  @override
  Future<String?> chooseOpenFile({List<String> extensions = const []}) async => path;
}

class _Clipboard extends SecureClipboard {
  final copied = <String>[];
  @override
  Future<void> copySecret(
    String value, {
    bool Function()? isCurrent,
    Duration? limit,
    bool autoGenerated = false,
  }) async {
    if (isCurrent?.call() ?? true) copied.add(value);
  }
}

