  testWidgets('mutations save immediately, serialize, survive reopen and retain dirty data on conflict', (
    tester,
  ) async {
    final backend = testBackend();
    addTearDown(backend.dispose);
    await backend.debugSignInDemoAndUnlock();
    await pumpApp(tester, backend);
    final container = ProviderScope.containerOf(tester.element(find.byType(Navigator).first));
    final manager = container.read(passwordManagerProvider);
    await tester.runAsync(() async {
      final session = await manager.open(KdbxSource.local(fixturePath), password: SecretText('fixture-password'));
      await Future.wait([
        manager.request(session, 'group', {'name': 'First'}),
        manager.request(session, 'group', {'name': 'Second'}),
      ]);
      expect(session.data['dirty'], isFalse);
      final original = File(fixturePath).readAsBytesSync();
      await File(fixturePath).writeAsBytes([1, 2, 3], flush: true);
      await expectLater(
        manager.request(session, 'group', {'name': 'Retained on failure'}),
        throwsA(isA<KdbxFailure>()),
      );
      expect(session.data['dirty'], isTrue);
      expect(session.saveError, isNotNull);
      expect(session.rows('groups').any((g) => g['label'] == 'Retained on failure'), isTrue);
      await File(fixturePath).writeAsBytes(original, flush: true);
      await manager.save(session);
      expect(session.data['dirty'], isFalse);
      expect(session.saveError, isNull);
      manager.lock(session.source);
      final reopened = await manager.open(KdbxSource.local(fixturePath), password: SecretText('fixture-password'));
      expect(reopened.rows('groups').map((g) => g['label']), containsAll(['First', 'Second', 'Retained on failure']));
    });
