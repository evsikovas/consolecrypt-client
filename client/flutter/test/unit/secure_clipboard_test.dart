import 'dart:math';

import 'package:consolecrypt/core/bridge/mapping.dart';
import 'package:consolecrypt/core/models/models.dart';
import 'package:consolecrypt/core/providers.dart';
import 'package:consolecrypt/core/security/secure_clipboard.dart';
import 'package:consolecrypt/core/util/value_stream.dart';
import 'package:flutter/services.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_test/flutter_test.dart';

import '../helpers/fake_native_clipboard.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();
  String value() => List.generate(32, (_) => Random.secure().nextInt(256)).join('-');
  const everywhere = TargetPlatformVariant({
    TargetPlatform.android,
    TargetPlatform.iOS,
    TargetPlatform.macOS,
    TargetPlatform.windows,
    TargetPlatform.linux,
  });

  testWidgets('a missing native handler fails closed on every platform', (tester) async {
    final messenger = TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger;
    var platformWrites = 0;
    messenger.setMockMethodCallHandler(SystemChannels.platform, (call) async {
      if (call.method == 'Clipboard.setData') platformWrites++;
      return null;
    });
    // No native handler registered on this platform.
    messenger.setMockMethodCallHandler(SecureClipboard.channel, (_) async => throw MissingPluginException());
    addTearDown(() {
      messenger.setMockMethodCallHandler(SystemChannels.platform, null);
      messenger.setMockMethodCallHandler(SecureClipboard.channel, null);
    });
    final owner = SecureClipboard();
    await expectLater(owner.copySecret(value()), throwsA(isA<MissingPluginException>()));
    await expectLater(owner.copyPrivate(value()), throwsA(isA<MissingPluginException>()));
    expect(platformWrites, 0, reason: 'never downgraded to an ordinary clipboard write');
    owner.dispose();
    await tester.pump();
  }, variant: everywhere);

  testWidgets('a native failure is reported and leaves nothing pending', (tester) async {
    final native = FakeNativeClipboard(text: 'Existing public clip')..install();
    native.failCopies = true;
    final store = _MemoryClearStore();
    final owner = SecureClipboard(store: store);
    await expectLater(owner.copySecret(value()), throwsA(isA<PlatformException>()));
    expect(native.text, 'Existing public clip');
    expect(store.record, isNull);
    owner.dispose();
    await tester.pump();
  });

  testWidgets('copySecret passes the deadline and autoGenerated; never reads the clipboard', (tester) async {
    final native = FakeNativeClipboard()..install();
    final store = _MemoryClearStore();
    final owner = SecureClipboard(clearAfter: const Duration(minutes: 5), store: store);
    final secret = value();
    await owner.copySecret(secret, autoGenerated: true);
    expect(native.lastSecret, {'text': secret, 'clearAfterMilliseconds': 300000, 'autoGenerated': true});
    expect(store.record, isNot(contains(secret)));
    expect(store.record, contains('"token":"c1"'));
    await owner.copySecret(value(), limit: const Duration(seconds: 30));
    expect(native.lastSecret!['clearAfterMilliseconds'], 30000);
    expect(native.lastSecret!['autoGenerated'], isFalse);
    await tester.pump(const Duration(seconds: 30));
    expect(native.text, isNull);
    expect(native.calls, ['copySecret', 'copySecret', 'clearIfOwned']);
    expect(native.dartReads, 0);
    expect(store.record, isNull);
    owner.dispose();
    await tester.pump();
  }, variant: everywhere);

  testWidgets('dispose clears a copied secret but preserves a newer clipboard value', (tester) async {
    final native = FakeNativeClipboard()..install();
    final first = SecureClipboard();
    await first.copySecret(value());
    first.dispose();
    await tester.pump();
    expect(native.text, isNull);

    final second = SecureClipboard();
    await second.copySecret(value());
    native.userCopies('A newer non-secret value');
    second.dispose();
    await tester.pump();
    expect(native.text, 'A newer non-secret value');
    expect(native.dartReads, 0);
  });

  testWidgets('clearNow reports cleared, foreign and gone', (tester) async {
    final native = FakeNativeClipboard()..install();
    final owner = SecureClipboard(clearAfter: const Duration(hours: 1));
    expect(await owner.clearNow(), isNull, reason: 'nothing pending');
    await owner.copySecret(value());
    expect(await owner.clearNow(), ClipboardClearResult.cleared);
    expect(native.text, isNull);
    expect(await owner.clearNow(), isNull, reason: 'cleared once');

    await owner.copySecret(value());
    native.userCopies('copied in another app');
    expect(await owner.clearNow(), ClipboardClearResult.foreign);
    expect(native.text, 'copied in another app');

    await owner.copySecret(value());
    native.systemClears();
    expect(await owner.clearNow(), ClipboardClearResult.gone);
    expect(native.dartReads, 0);
    owner.dispose();
    await tester.pump();
  });

  testWidgets('private and plain copies cancel the pending clear and are never cleared', (tester) async {
    final native = FakeNativeClipboard()..install();
    final store = _MemoryClearStore();
    final owner = SecureClipboard(clearAfter: const Duration(seconds: 2), store: store);
    await owner.copySecret(value());
    await owner.copyPrivate('terminal selection');
    expect(store.record, isNull);
    await tester.pump(const Duration(seconds: 3));
    expect(native.text, 'terminal selection');

    await owner.copySecret(value());
    await owner.copyPlain('ssh-ed25519 AAAA public');
    expect(store.record, isNull);
    await tester.pump(const Duration(seconds: 3));
    expect(native.text, 'ssh-ed25519 AAAA public');
    expect(native.calls, ['copySecret', 'copyPrivate', 'copySecret', 'forget']);
    owner.dispose();
    await tester.pump();
    expect(native.text, 'ssh-ed25519 AAAA public');
  });

  testWidgets('changing local settings retains the clipboard owner and the pending deadline', (tester) async {
    final native = FakeNativeClipboard()..install();
    final settings = ValueStreamController(const LocalSettings(clipboardClearSeconds: 30));
    final container = ProviderContainer(overrides: [localSettingsProvider.overrideWith((ref) => settings.stream)]);
    final subscription = container.listen(secureClipboardProvider, (_, _) {});
    await tester.pump();
    final owner = container.read(secureClipboardProvider);
    await owner.copySecret(value());
    settings.value = const LocalSettings(clipboardClearSeconds: 60, terminalFontSize: 17);
    await tester.pump();
    expect(identical(container.read(secureClipboardProvider), owner), isTrue);
    await tester.pump(const Duration(seconds: 29));
    expect(native.text, isNotNull);
    await tester.pump(const Duration(seconds: 1));
    expect(native.text, isNull);
    expect(owner.clearAfter, const Duration(minutes: 1));
    subscription.close();
    container.dispose();
    await settings.close();
  });

  testWidgets('the timer clears only the last copied secret', (tester) async {
    final native = FakeNativeClipboard()..install();
    final owner = SecureClipboard(clearAfter: const Duration(seconds: 2));
    await owner.copySecret(value());
    await tester.pump(const Duration(seconds: 1));
    await owner.copySecret(value());
    await tester.pump(const Duration(seconds: 1));
    expect(native.text, isNotNull);
    await tester.pump(const Duration(seconds: 1));
    expect(native.text, isNull);
    expect(native.calls.where((c) => c == 'clearIfOwned'), hasLength(1));
    owner.dispose();
  });

  testWidgets('a failed native clear is retried, then left for the next start', (tester) async {
    final messenger = TestDefaultBinaryMessengerBinding.instance.defaultBinaryMessenger;
    var clears = 0;
    messenger.setMockMethodCallHandler(SecureClipboard.channel, (call) async {
      if (call.method == 'copySecret') return 'c1';
      clears++;
      throw PlatformException(code: 'busy');
    });
    addTearDown(() => messenger.setMockMethodCallHandler(SecureClipboard.channel, null));
    final store = _MemoryClearStore();
    final owner = SecureClipboard(clearAfter: const Duration(seconds: 2), store: store);
    await owner.copySecret(value());
    await tester.pump(const Duration(seconds: 2));
    for (var i = 0; i < 4; i++) {
      await tester.pump(const Duration(seconds: 10));
    }
    expect(clears, 4);
    expect(store.record, contains('"token":"c1"'));
    owner.dispose();
    await tester.pump();
  });

  test('stored auto-clear durations map to the nearest choice not shorter', () {
    expect(clipboardClearChoices, [30, 60, 120, 300, 900, 3600, 28800, 86400]);
    expect(clipboardClearSeconds(10), 30);
    expect(clipboardClearSeconds(15), 30);
    expect(clipboardClearSeconds(30), 30);
    expect(clipboardClearSeconds(45), 60);
    expect(clipboardClearSeconds(120), 120);
    expect(clipboardClearSeconds(121), 300);
    expect(clipboardClearSeconds(7200), 28800);
    expect(clipboardClearSeconds(999999), 86400);
    expect(clipboardClearSeconds(-1), 30);
    // Settings saved by older versions (15/30/60/120) load as choices.
    for (final (old, mapped) in [(10, 30), (15, 30), (30, 30), (60, 60), (120, 120), (90000, 86400)]) {
      expect(localSettingsFromJson({'clipboard_clear_seconds': old}).clipboardClearSeconds, mapped);
    }
    expect(localSettingsFromJson({}).clipboardClearSeconds, 30);
  });

  testWidgets('a pending clear survives a restart and never clears foreign content', (tester) async {
    final native = FakeNativeClipboard()..install();
    final store = _MemoryClearStore();
    var now = DateTime.utc(2026, 10, 22, 12);
    final secret = value();
    final first = SecureClipboard(clearAfter: const Duration(hours: 1), store: store, now: () => now);
    await first.copySecret(secret);
    final record = store.record!;
    expect(record, isNot(contains(secret)));
    // The app is killed: no dispose, no timer.

    // Restart before the deadline: nothing is cleared yet.
    now = now.add(const Duration(minutes: 30));
    final second = SecureClipboard(store: store, now: () => now);
    await second.clearExpired();
    expect(native.text, secret);
    expect(store.record, record);
    await tester.pump(const Duration(minutes: 30));
    expect(native.text, isNull, reason: 're-armed for the remaining 30 minutes');
    expect(store.record, isNull);
    second.dispose();

    // Restart after the deadline with our clip still there: cleared.
    await first.copySecret(secret);
    final third = SecureClipboard(store: store, now: () => now.add(const Duration(hours: 2)));
    await third.clearExpired();
    expect(native.text, isNull);
    expect(store.record, isNull);

    // Foreign content after the deadline stays; the record is dropped.
    await first.copySecret(secret);
    native.userCopies('copied by the user later');
    await third.clearExpired();
    expect(native.text, 'copied by the user later');
    expect(store.record, isNull);

    // Malformed records and 0.9.1 hash records are dropped untouched.
    for (final old in ['not json', '{"deadline_ms":1,"sha256":"${'0' * 64}"}']) {
      store.record = old;
      await third.clearExpired();
      expect(native.text, 'copied by the user later');
      expect(store.record, isNull);
    }
    expect(native.dartReads, 0);
    third.dispose();
    first.dispose();
    await tester.pump();
  });
}

final class _MemoryClearStore implements ClipboardClearStore {
  String? record;
  @override
  Future<String?> read() async => record;
  @override
  Future<void> write(String? record) async => this.record = record;
}
