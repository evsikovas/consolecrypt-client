//! One purpose-specific handoff to the actual Core Files/Permit owner.
//! No pathname input, plaintext callback, second file owner or cleanup observer.
use super::*;
use crate::{CollectorCredentialTarget, RegisteredCredentialWriter, Timestamp};

/// Public metadata of a completed private-file write, NOT a running/cleanup
/// receipt. Construction is possible only through the actual registered writer.
/// Private config may use its projection; never serialize this into an audit.
pub(crate) struct RegisteredCollectorCredential<'a> {
    scope_hash: Hash,
    target: CollectorCredentialTarget,
    username: String,
    leaf: String,
    expires_at: Timestamp,
    permit: &'a CollectorServicePermit,
}
impl<'a> OpenedCollectorCredential<'a> {
    pub(crate) fn scope_hash(&self) -> Result<Hash> { self.scope.body.digest() }
    pub(crate) fn target(&self) -> &CollectorCredentialTarget { &self.scope.body.target }
    pub(crate) fn effective_expiry(&self) -> Timestamp {
        self.material_expires_at.min(self.scope.body.expires_at)
    }

    /// Must run inside Core Files::with_original_credential_session. In a
    /// multi-secret batch, process effective expiries in nonincreasing order:
    /// Core's strict narrow operation never increases a previously held end.
    pub(crate) fn write_registered<S: CompareAndSwap>(
        self, writer: &mut RegisteredCredentialWriter<'_, '_, S>,
    ) -> Result<RegisteredCollectorCredential<'a>> {
        if !writer.matches_original_permit(self.permit) { return Err(Error::WrongState); }
        let scope_hash = self.scope.body.digest()?;
        let expires_at = self.effective_expiry();
        writer.narrow_expiry(expires_at)?;
        let now = writer.recheck()?;
        let written = self.material.with_secret(&self.expected, now.0.seconds(), |raw| {
            if !cc_crypto_core::collector_basic_password_supported(raw) { return Err(Error::InvalidWire); }
            // Once writer creation is attempted, a lost/failed result is
            // unknown. Core already registered the original cleanup custody.
            writer.write_scope_password(scope_hash, raw).map_err(|_| Error::UncertainCommit)
        }).map_err(|_| Error::WrongClaim)?;
        let leaf = written?;
        writer.recheck().map_err(|_| Error::UncertainCommit)?;
        let expected_leaf = format!("credential-{}.password", hex::encode(scope_hash.as_bytes()));
        if leaf != expected_leaf { return Err(Error::UncertainCommit); }
        Ok(RegisteredCollectorCredential { scope_hash, target: self.scope.body.target,
            username: self.scope.body.username, leaf, expires_at, permit: self.permit })
    }
}
impl RegisteredCollectorCredential<'_> {
    pub(crate) fn scope_hash(&self) -> Hash { self.scope_hash }
    pub(crate) fn target(&self) -> &CollectorCredentialTarget { &self.target }
    pub(crate) fn expires_at(&self) -> Timestamp { self.expires_at }

    /// Relative filename is generated by the actual original Core session.
    /// The fixed component config resolves it within that SAME private session.
    /// Caller must retain Core Access and its narrowed original kernel deadline
    /// through config/pre-exec; this projection grants no later service access.
    pub(crate) fn private_auth_projection<S: CompareAndSwap>(&self,
        writer: &mut RegisteredCredentialWriter<'_, '_, S>) -> Result<serde_json::Value> {
        if !writer.matches_original_permit(self.permit) { return Err(Error::WrongState); }
        writer.narrow_expiry(self.expires_at)?;
        writer.recheck()?;
        let value = serde_json::json!({"basic_auth":{"username":self.username,"password_file":self.leaf}});
        writer.recheck()?;
        Ok(value)
    }
}
